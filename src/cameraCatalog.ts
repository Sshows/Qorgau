/** Verified public still previews; a thumbnail never confirms video playback. */
export function cameraPreviewUrl(camera: Pick<CameraRecord, "stream_type" | "stream_url">): string | undefined {
  if (camera.stream_type === "image") return camera.stream_url;
  const url = new URL(camera.stream_url);
  if (url.hostname === "ipcam.kz" && /^\/cam(1|5|6)\/index\.m3u8$/.test(url.pathname)) return new URL("preview.jpg", url).href;
  return undefined;
}
